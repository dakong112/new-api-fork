func newAccessTokenScopeTestEngine(t *testing.T) *gin.Engine {
	t.Helper()
	gin.SetMode(gin.TestMode)
	engine := gin.New()
	// A permission route that is also in the static table panics here.
	require.NotPanics(t, func() {
		SetApiRouter(engine)
		SetDashboardRouter(engine)
		SetRelayRouter(engine)
		SetTaskPluginProtocolRouter(engine)
		SetVideoRouter(engine)
		SetTaskRouter(engine)
	})
	return engine
}

func TestAccessTokenRouteRulesCoverEveryDashboardRoute(t *testing.T) {
	engine := newAccessTokenScopeTestEngine(t)
	exempt := map[string]bool{}
	for _, key := range accessTokenExemptRoutes {
		exempt[key] = true
	}
	registered := map[string]bool{}
	panel := map[string]bool{}
	for _, route := range engine.Routes() {
		if !strings.HasPrefix(route.Path, "/api/") && !strings.HasPrefix(route.Path, "/pg/") {
			continue
		}
		key := route.Method + " " + route.Path
		registered[key] = true
		if !exempt[key] {
			panel[key] = true
		}
	}
	for _, key := range accessTokenExemptRoutes {
		assert.True(t, registered[key], "exempt route %s is no longer registered", key)
	}

	declared := map[string]int{}
	for _, key := range middleware.AccessTokenRouteRuleKeys() {
		declared[key]++
	}
	for key := range panel {
		assert.Equal(t, 1, declared[key], "panel route %s must be declared exactly once", key)
	}
	for key := range declared {
		assert.True(t, panel[key], "declared route %s is not a registered panel route", key)
	}

	permissionRoutes := map[string]authz.Permission{}
	for _, route := range channelPermissionRoutes {
		permissionRoutes[route.method+" "+joinPaths("/api/channel", route.path)] = route.permission
	}
	for key, permission := range accessTokenHelperRoutes {
		permissionRoutes[key] = permission
	}
	for key, permission := range permissionRoutes {
		rule, ok := middleware.AccessTokenRouteRule(key)
		require.True(t, ok, key)
		assert.Equal(t, "scope", rule.Kind(), key)
		assert.Equal(t, service.AccessTokenScopeOf(permission), rule.Scope(), key)
	}
}

func TestAccessTokenCatalogCoversEveryPermission(t *testing.T) {
	catalog := service.AccessTokenCatalog(1, common.RoleRootUser)
	scopes := map[string]bool{}
	resources := map[string]int{}
	for _, group := range catalog {
		for _, resource := range group.Resources {
			resources[resource.Resource]++
			for _, action := range resource.Actions {
				scopes[resource.Resource+":"+action.Action] = true
			}
		}
	}
	for _, resource := range authz.Catalog() {
		for _, action := range resource.Actions {
			scope := service.AccessTokenScopeOf(authz.Permission{Resource: resource.Resource, Action: action.Action})
			// Other applications enforce their own codes; they are never token scopes.
			assert.Equal(t, resource.App == "", scopes[scope], scope)
		}
	}
	for resource, count := range resources {
		assert.Equal(t, 1, count, "resource %s appears in more than one catalog entry", resource)
	}
}

func TestAccessTokenVerificationScopesAreAllListed(t *testing.T) {
	files, err := filepath.Glob("../service/*.go")
	require.NoError(t, err)
	fileSet := token.NewFileSet()
	var scopes []string
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		parsed, err := parser.ParseFile(fileSet, file, nil, 0)
		require.NoError(t, err)
		for _, declaration := range parsed.Decls {
			general, ok := declaration.(*ast.GenDecl)
			if !ok || general.Tok != token.CONST {
				continue
			}
			for _, spec := range general.Specs {
				value := spec.(*ast.ValueSpec)
				for i, name := range value.Names {
					if !strings.HasPrefix(name.Name, "VerificationScope") || i >= len(value.Values) {
						continue
					}
					literal, ok := value.Values[i].(*ast.BasicLit)
					require.True(t, ok, name.Name)
					scope, err := strconv.Unquote(literal.Value)
					require.NoError(t, err)
					scopes = append(scopes, scope)
				}
			}
		}
	}
	require.NotEmpty(t, scopes)
	for _, scope := range scopes {
		_, listed := service.AccessTokenVerificationScope(scope)
		assert.True(t, listed, "verification scope %s has no access token rule", scope)
	}
}

func TestSSOClientCORSOnSignInRoutes(t *testing.T) {
	previous := setting.SSOClients2JsonString()
	t.Cleanup(func() { _ = setting.UpdateSSOClientsByJsonString(previous) })
	require.NoError(t, setting.UpdateSSOClientsByJsonString(`[{"client_id":"infinite","secret_hash":"`+setting.SSOSecretHash("s")+`","redirect_uris":["https://app.example.com/sso/callback"]}]`))
	engine := newAccessTokenScopeTestEngine(t)

	cases := []struct {
		name, method, path, origin string
		wantStatus                 int // 0 = any
		wantOrigin                 string
	}{
		{"preflight sso code", http.MethodOptions, "/api/sso/code", "https://app.example.com", http.StatusNoContent, "https://app.example.com"},
		{"preflight login", http.MethodOptions, "/api/user/login", "https://app.example.com", http.StatusNoContent, "https://app.example.com"},
		{"preflight other origin", http.MethodOptions, "/api/sso/code", "https://evil.example.com", http.StatusNoContent, ""},
		{"preflight prefix origin", http.MethodOptions, "/api/sso/code", "https://app.example.com.evil.com", http.StatusNoContent, ""},
		{"login response", http.MethodPost, "/api/user/login", "https://app.example.com", 0, "https://app.example.com"},
		{"status response", http.MethodGet, "/api/status", "https://app.example.com", 0, "https://app.example.com"},
		{"login other origin", http.MethodPost, "/api/user/login", "https://evil.example.com", 0, ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			request := httptest.NewRequest(tc.method, tc.path, strings.NewReader(`{}`))
			request.Header.Set("Origin", tc.origin)
			request.Header.Set("Content-Type", "application/json")
			response := httptest.NewRecorder()
			engine.ServeHTTP(response, request)
			if tc.wantStatus != 0 {
				assert.Equal(t, tc.wantStatus, response.Code)
			}
			assert.Equal(t, tc.wantOrigin, response.Header().Get("Access-Control-Allow-Origin"))
			assert.Empty(t, response.Header().Get("Access-Control-Allow-Credentials"))
			if tc.method == http.MethodOptions && tc.wantOrigin != "" {
				assert.Contains(t, response.Header().Get("Access-Control-Allow-Headers"), "Authorization")
			}
		})
	}
}
